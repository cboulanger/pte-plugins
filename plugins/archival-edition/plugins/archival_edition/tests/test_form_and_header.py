"""
Tests for reading the description form and building the TEI header.

The fixture sample-letter.pdf is generated by scripts/make_sample_pdf.py.
"""

import unittest
from pathlib import Path

import pymupdf
from lxml import etree

from archival_edition.form_parser import build_form_prompt, count_text_form_pages, parse_form_response, parse_form_tables
from archival_edition.header_builder import build_class_decl, build_facsimile, build_scaffold_header, parse_doc_type
from archival_edition.values import parse_date, parse_image_files, parse_languages, parse_name, parse_value

FIXTURES = Path(__file__).parent / "fixtures"
SCHEMA = Path(__file__).parent.parent / "static" / "schema" / "tei-archival.rng"
TEI_NS = "http://www.tei-c.org/ns/1.0"
NS = {"tei": TEI_NS}


class TestValues(unittest.TestCase):
    """Form conventions: [inferred], ?, dates, names, languages."""

    def test_inferred_and_uncertain(self):
        value = parse_value("[1962-03?]")
        self.assertEqual((value.text, value.inferred, value.uncertain), ("1962-03", True, True))
        self.assertFalse(parse_value("  "))

    def test_dates(self):
        self.assertEqual(parse_date("1962-03-12").attrs, {"when": "1962-03-12"})
        self.assertEqual(parse_date("1962-03/1962-05").attrs, {"notBefore": "1962-03", "notAfter": "1962-05"})
        self.assertEqual(parse_date("spring 1962").attrs, {})
        self.assertIsNone(parse_date(""))

    def test_names(self):
        person = parse_name("Kovács, János (GND 118540238; Q42)")
        assert person is not None
        self.assertEqual((person.surname, person.forename, person.is_person), ("Kovács", "János", True))
        self.assertEqual(person.refs, ["https://d-nb.info/gnd/118540238", "http://www.wikidata.org/entity/Q42"])
        org = parse_name("Magyar Tudományos Akadémia")
        assert org is not None
        self.assertFalse(org.is_person)

    def test_languages_and_images(self):
        self.assertEqual(parse_languages("Hungarian, English"), [("hu", "Hungarian"), ("en", "English")])
        self.assertEqual(parse_languages("hu; de"), [("hu", "hu"), ("de", "de")])
        self.assertEqual(parse_image_files("IMG_1 = 1r; IMG_2"), [("IMG_1", "1r"), ("IMG_2", "")])

    def test_doc_type(self):
        self.assertEqual(parse_doc_type("conference program").category, "program")
        other = parse_doc_type("other (newspaper clipping)")
        self.assertEqual((other.category, other.text), ("other", "newspaper clipping"))


class TestFormParser(unittest.TestCase):
    """Reading the form from the text layer of the sample PDF."""

    def setUp(self):
        self.doc = pymupdf.open(FIXTURES / "sample-letter.pdf")

    def tearDown(self):
        self.doc.close()

    def test_counts_form_pages_before_photos(self):
        self.assertEqual(count_text_form_pages(self.doc), self.doc.page_count - 2)

    def test_reads_entries(self):
        fields = parse_form_tables(self.doc, count_text_form_pages(self.doc))
        self.assertEqual(fields["doc_id"], "TEST-0001")
        self.assertEqual(fields["supplied_title"], "Letter from Teszt Elek to Jane Example, 12 March 1962")
        # ligatures (tt, ff, ti) must not be garbled
        self.assertEqual(fields["extent"], "1 leaf, 2 pages written")
        self.assertEqual(fields["keywords"], "comparative law; conference; offprint")
        self.assertEqual(fields["sent_date"], "[1962-03-12?]")
        self.assertNotIn("title", fields)
        self.assertNotIn("event", fields)

    def test_scanned_form_response(self):
        self.assertIn('"doc_id": Document ID', build_form_prompt())
        pages, fields = parse_form_response('Here: {"form_pages": 3, "fields": {"doc_id": "X-1", "bogus": "y", "place": ""}}')
        self.assertEqual((pages, fields), (3, {"doc_id": "X-1"}))


class TestHeaderBuilder(unittest.TestCase):
    """The header built from the sample form validates and maps the form's TEI paths."""

    @classmethod
    def setUpClass(cls):
        with pymupdf.open(FIXTURES / "sample-letter.pdf") as doc:
            cls.fields = parse_form_tables(doc, count_text_form_pages(doc))
        header, _ = build_scaffold_header(cls.fields, "f-test", "Test project")
        encoding_desc = etree.SubElement(header, "encodingDesc")
        encoding_desc.append(build_class_decl())
        tei = etree.Element("TEI", nsmap={None: TEI_NS})  # type: ignore[dict-item]
        tei.append(header)
        tei.append(build_facsimile(cls.fields, 2)[0])
        cls.tei = etree.fromstring(etree.tostring(tei))

    def xpath(self, path: str) -> list[str]:
        return [str(v) for v in self.tei.xpath(path, namespaces=NS)]

    def test_validates_against_schema(self):
        schema = etree.RelaxNG(etree.parse(str(SCHEMA)))
        self.assertTrue(schema.validate(self.tei), schema.error_log)

    def test_maps_form_fields(self):
        self.assertEqual(self.xpath("//tei:titleStmt/tei:title[@type='supplied']/text()"), ["Letter from Teszt Elek to Jane Example, 12 March 1962"])
        self.assertEqual(self.xpath("//tei:publicationStmt/tei:idno/text()"), ["TEST-0001"])
        self.assertEqual(self.xpath("//tei:availability/@status"), ["unknown"])
        self.assertEqual(self.xpath("//tei:msIdentifier/tei:settlement/text()"), ["Budapest"])
        self.assertEqual(self.xpath("//tei:origDate/@when"), ["1962-03-12"])
        self.assertEqual(self.xpath("//tei:origDate/@evidence"), ["internal"])
        self.assertEqual(self.xpath("//tei:objectDesc/@form"), ["original"])
        self.assertEqual(self.xpath("//tei:langUsage/tei:language/@ident"), ["hu", "en"])
        self.assertEqual(self.xpath("//tei:catRef/@target"), ["#doctype-letter"])
        self.assertEqual(self.xpath("//tei:correspAction[@type='sent']/tei:date/@cert"), ["low"])
        self.assertEqual(self.xpath("//tei:correspAction[@type='received']/tei:persName/tei:surname/text()"), ["Example"])
        self.assertEqual(self.xpath("//tei:surface/@n"), ["1r", "1v"])
        self.assertEqual(self.xpath("//tei:respStmt/tei:resp/@when"), ["2026-10-01", "2026-10-02"])


if __name__ == "__main__":
    unittest.main()
